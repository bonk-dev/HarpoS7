    private static int Crumb(byte value, int j) => ((value >> j) & 1) | (((value >> (j + 4)) & 1) << 1);

    internal static void Execute(Span<byte> destination, ReadOnlySpan<byte> challenge)
    {
        Span<byte> state = stackalloc byte[8];
        Span<byte> next = stackalloc byte[8];
        for (var i = 0; i < 8; i++)
            state[i] = (byte)(InverseSbox[challenge[i + 2] ^ InputKey[i]] ^ InverseSbox[challenge[i + 10] ^ InputKey[i + 8]]);
        for (var round = 0; round < 13; round++)
        {
            for (var i = 0; i < 8; i++)
            {
                var row = round * 8 + i;
                var input = 0;
                for (var lane = 0; lane < 4; lane++)
                    input |= Crumb(state[Wiring[row, lane + 1]], Wiring[row, 0]) << (2 * lane);
                next[i] = InverseSbox[input ^ RoundKeys[row]];
            }
            next.CopyTo(state);
        }
        for (var i = 0; i < 8; i++)
        {
            var high = EncodeNibble(state, i * 2);
            var low = EncodeNibble(state, i * 2 + 1);
            destination[i] = (byte)((high << 4) | low);
        }
    }

    private static byte EncodeNibble(ReadOnlySpan<byte> state, int n)
    {
        var j = OutputCrumbs[n, 0];
        var input = Crumb(state[OutputCrumbs[n, 1]], j) | (Crumb(state[OutputCrumbs[n, 2]], j) << 2);
        return OutputEncoding[n, input];
    }
